"""
api.py
======
FastAPI prediction API for the Smart Hygiene Risk Prediction System.

Endpoints
---------
GET  /          — Welcome message and project info.
GET  /health    — API health status and model load status.
POST /predict   — Accept a validated hygiene inspection record and return
                  the predicted risk category with class probabilities.

Usage
-----
    uvicorn api:app --reload

Then visit http://127.0.0.1:8000/docs for the interactive Swagger UI.

DISCLAIMER
----------
Predictions are from a model trained on SYNTHETIC, rule-generated data.
They are for educational demonstration only and MUST NOT be used as
official safety certifications or public-health assessments.
"""

from __future__ import annotations

import os
import sys
import traceback
from contextlib import asynccontextmanager
from typing import Optional

from fastapi import FastAPI, HTTPException, status
from pydantic import BaseModel, Field, field_validator

# ── ensure src/ is on the path ────────────────────────────────────────────────
_HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, _HERE)

from src.predict import load_model, predict, VALID_WASTE_LEVELS, VALID_WATER_OPTIONS

# ── model bundle (loaded once at startup) ─────────────────────────────────────
MODEL_BUNDLE = None  # type: dict | None
MODEL_PATH = os.path.join(_HERE, "models", "hygiene_risk_model.joblib")


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Load the model pipeline when the API starts."""
    global MODEL_BUNDLE
    try:
        MODEL_BUNDLE = load_model(MODEL_PATH)
        print(f"[OK] Model loaded: {MODEL_BUNDLE.get('model_name')}")
    except FileNotFoundError as e:
        print(f"[WARN] Model not found at startup: {e}")
        print("       Run  python src/train_model.py  first.")
    yield
    # Cleanup (none required)


# ── FastAPI application ───────────────────────────────────────────────────────

app = FastAPI(
    title="Smart Hygiene Risk Prediction API",
    description=(
        "REST API for predicting hygiene risk categories of facility inspections. "
        "**DISCLAIMER**: Predictions are generated by a model trained on **synthetic, "
        "rule-generated data** for educational purposes only. Do NOT use predictions "
        "as official hygiene certifications or public-health assessments."
    ),
    version="1.0.0",
    lifespan=lifespan,
)


# ── Pydantic request / response models ───────────────────────────────────────

class InspectionRecord(BaseModel):
    """
    Validated hygiene inspection input record.

    All fields are required except inspection_month and inspection_dayofweek,
    which default to mid-year / mid-week values when not provided.
    """

    cleanliness_score: float = Field(
        ..., ge=0, le=100,
        description="Overall cleanliness score (0 = worst, 100 = best).",
        examples=[35],
    )
    odor_score: float = Field(
        ..., ge=0, le=10,
        description="Odor intensity score (0 = no odor, 10 = severe odor).",
        examples=[8],
    )
    waste_level: str = Field(
        ..., description="Waste accumulation level: Low | Medium | High.",
        examples=["High"],
    )
    water_availability: str = Field(
        ..., description="Water availability at the facility: Yes | No.",
        examples=["No"],
    )
    footfall: float = Field(
        ..., ge=0,
        description="Estimated daily footfall (number of visitors).",
        examples=[250],
    )
    complaints: float = Field(
        ..., ge=0,
        description="Number of registered hygiene complaints.",
        examples=[12],
    )
    inspection_month: Optional[int] = Field(
        default=6, ge=1, le=12,
        description="Month of inspection (1–12). Defaults to 6 (June).",
    )
    inspection_dayofweek: Optional[int] = Field(
        default=2, ge=0, le=6,
        description="Day of week (0=Monday … 6=Sunday). Defaults to 2 (Wednesday).",
    )

    @field_validator("waste_level")
    @classmethod
    def validate_waste_level(cls, v: str) -> str:
        if v not in VALID_WASTE_LEVELS:
            raise ValueError(f"waste_level must be one of {VALID_WASTE_LEVELS}. Got: '{v}'")
        return v

    @field_validator("water_availability")
    @classmethod
    def validate_water_availability(cls, v: str) -> str:
        if v not in VALID_WATER_OPTIONS:
            raise ValueError(f"water_availability must be one of {VALID_WATER_OPTIONS}. Got: '{v}'")
        return v

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "cleanliness_score": 35,
                    "odor_score": 8,
                    "waste_level": "High",
                    "water_availability": "No",
                    "footfall": 250,
                    "complaints": 12,
                }
            ]
        }
    }


class PredictionResponse(BaseModel):
    """Prediction API response model."""
    predicted_class: str
    probabilities: dict[str, float]
    model_name: str
    disclaimer: str


class HealthResponse(BaseModel):
    """Health check response model."""
    status: str
    model_loaded: bool
    model_name: Optional[str]


# ── endpoints ─────────────────────────────────────────────────────────────────

@app.get(
    "/",
    summary="Welcome",
    response_description="Welcome message and project information.",
)
def root():
    """
    Return a welcome message and key project details.

    This endpoint confirms the API is running.
    """
    return {
        "message": "Welcome to the Smart Hygiene Risk Prediction API",
        "project": "Pugarch Internship — Day 10 AI/ML Assignment",
        "version": "1.0.0",
        "endpoints": {
            "GET  /":        "This welcome message.",
            "GET  /health":  "API health and model status.",
            "POST /predict": "Predict hygiene risk for an inspection record.",
        },
        "docs": "Visit /docs for the interactive Swagger UI.",
        "disclaimer": (
            "Predictions are from a model trained on synthetic data "
            "for educational purposes only."
        ),
    }


@app.get(
    "/health",
    response_model=HealthResponse,
    summary="Health Check",
    response_description="API health status and model load status.",
)
def health():
    """
    Return the health status of the API and whether the trained model is loaded.
    """
    return HealthResponse(
        status="ok",
        model_loaded=MODEL_BUNDLE is not None,
        model_name=MODEL_BUNDLE.get("model_name") if MODEL_BUNDLE else None,
    )


@app.post(
    "/predict",
    response_model=PredictionResponse,
    summary="Predict Hygiene Risk",
    response_description="Predicted hygiene risk category with class probabilities.",
    status_code=status.HTTP_200_OK,
)
def predict_endpoint(record: InspectionRecord):
    """
    Accept a validated hygiene inspection record and return the predicted
    hygiene risk category (`Low`, `Medium`, or `High`) along with class
    probabilities.

    **Important**: This API uses a model trained on synthetic, rule-generated
    data. Predictions are for educational demonstration only.

    **Request body fields:**
    - `cleanliness_score`: 0–100 (required)
    - `odor_score`: 0–10 (required)
    - `waste_level`: Low | Medium | High (required)
    - `water_availability`: Yes | No (required)
    - `footfall`: ≥ 0 (required)
    - `complaints`: ≥ 0 (required)
    - `inspection_month`: 1–12 (optional, default=6)
    - `inspection_dayofweek`: 0–6 (optional, default=2)
    """
    if MODEL_BUNDLE is None:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail=(
                "Model is not loaded. "
                "Please run  python src/train_model.py  first, then restart the API."
            ),
        )

    try:
        result = predict(record.model_dump(), MODEL_BUNDLE)
    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=str(e),
        )
    except Exception:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="An unexpected error occurred during prediction. Check server logs.",
        )

    return PredictionResponse(**result)
